-- Baseline schema. Column names follow Spring Boot's snake_case naming of the JPA entities; Hibernate validates against this on startup.
create table if not exists users (
  id bigint generated by default as identity primary key,
  name varchar(255),
  email varchar(255) not null unique,
  password_hash varchar(255) not null,
  role varchar(255),
  created_at timestamp(6) with time zone
);

create table if not exists drivers (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references users (id),
  vehicle varchar(255),
  plate varchar(255),
  online boolean not null default false,
  lat double precision,
  lng double precision,
  location_at timestamp(6) with time zone,
  rating_avg double precision not null default 5.0,
  rating_count integer not null default 0
);

create table if not exists rides (
  id bigint generated by default as identity primary key,
  version bigint,
  rider_id bigint not null references users (id),
  driver_id bigint references drivers (id),
  pickup_name varchar(255),
  drop_name varchar(255),
  pickup_lat double precision not null,
  pickup_lng double precision not null,
  drop_lat double precision not null,
  drop_lng double precision not null,
  distance_km double precision not null,
  fare numeric(10, 2),
  vehicle_type varchar(255),
  status varchar(255),
  otp varchar(255),
  promo_code varchar(255),
  created_at timestamp(6) with time zone
);
create index if not exists idx_rides_status_created on rides (status, created_at);
create index if not exists idx_rides_rider on rides (rider_id);
create index if not exists idx_rides_driver on rides (driver_id);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  ride_id bigint not null unique references rides (id),
  amount_paise bigint not null,
  stripe_payment_intent_id varchar(255) unique,
  status varchar(255),
  created_at timestamp(6) with time zone
);

create table if not exists ratings (
  id bigint generated by default as identity primary key,
  ride_id bigint not null unique references rides (id),
  stars integer not null,
  comment varchar(500)
);

create table if not exists promo_codes (
  code varchar(255) primary key,
  percent_off integer not null,
  max_discount numeric(38, 2),
  active boolean not null default false
);

create table if not exists support_tickets (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users (id),
  ride_id bigint references rides (id),
  subject varchar(255),
  body varchar(2000),
  status varchar(255),
  created_at timestamp(6) with time zone
);
create index if not exists idx_tickets_user on support_tickets (user_id);

create table if not exists password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users (id),
  token_hash varchar(64) not null unique,
  expires_at timestamp(6) with time zone not null,
  used boolean not null default false
);
